def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    zpath = os.path.join(root, 'translations', 'zh.json')
    data = json.load(open(zpath, encoding='utf-8'))
    missing = open(os.path.join(root, 'extract', 'missing_translations.txt'), encoding='utf-8').read().split('\n')
    added = 0
    gaps = []
    for line in missing:
        if not line.strip():
            continue
        s = line.strip()
        zh = ADD.get(s)
        if not zh:
            if s not in gaps:
                gaps.append(s)
            continue
        for key in {line, s}:
            if key not in data:
                data[key] = zh
                added += 1
    # also apply any ADD entries that were not in the missing list at all
    for k, zh in ADD.items():
        if k not in data:
            data[k] = zh
            added += 1
    json.dump(data, open(zpath, 'w', encoding='utf-8'), ensure_ascii=False, indent=2, sort_keys=True)
    print('added=%d total=%d' % (added, len(data)))
    print('untranslated candidates left=%d' % len(gaps))
    for g in gaps[:40]:
        print('  TODO:', repr(g))

if __name__ == '__main__':
    main()

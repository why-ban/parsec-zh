#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate src/translations.h from translations/zh.json.
Emits EN/ZH tables and the ImWchar glyph range array covering ASCII + used CJK."""
import json, os, sys

def cstr(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch == '"': out.append('\\"')
        elif ch == '\\': out.append('\\\\')
        elif ch == '\n': out.append('\\n')
        elif ch == '\r': out.append('\\r')
        elif ch == '\t': out.append('\\t')
        elif o < 0x20: out.append('\\x%02x' % o)
        else:
            for b in ch.encode('utf-8'):
                out.append('\\x%02x' % b)
    # join: use explicit escapes concatenated (valid string literal)
    return '"' + ''.join(out) + '"'

def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    data = json.load(open(os.path.join(root, 'translations', 'zh.json'), encoding='utf-8'))
    items = [(k, v) for k, v in data.items() if k and v and k != v]
    # sort by length desc so longer strings can take precedence if needed
    items.sort(key=lambda kv: len(kv[0]), reverse=True)

    chars = set()
    for en, zh in items:
        for ch in zh:
            o = ord(ch)
            if o > 0x7F:
                chars.add(o)
    # Build ImWchar ranges: ASCII, Latin-1 supplement-ish, punctuation, then used CJK as ranges
    ranges = []
    ranges.append((0x0020, 0x007E))
    ranges.append((0x00A0, 0x00FF))
    ranges.append((0x2000, 0x206F))
    ranges.append((0x3000, 0x30FF))
    ranges.append((0x31F0, 0x31FF))
    ranges.append((0xFF00, 0xFFEF))
    cjk = sorted(c for c in chars if c >= 0x2E80)
    # compress into ranges
    i = 0
    while i < len(cjk):
        j = i
        while j + 1 < len(cjk) and cjk[j+1] == cjk[j] + 1:
            j += 1
        ranges.append((cjk[i], cjk[j]))
        i = j + 1
    ranges.sort()

    # ---- BROAD ranges: common Simplified Chinese (GB2312 level-1, 3755 chars)
    # PLUS every CJK codepoint used by our own translations, so a dictionary word
    # can never be missing a glyph at small sizes (GB2312 level-1 alone does not
    # cover e.g. 渲). Plus punctuation, so dynamic text (names, chat) can draw.
    common = set()
    for hi in range(0xB0, 0xD8):   # GB2312 level-1 = 3755 most common simplified chars
        for lo in range(0xA1, 0xFF):
            try:
                ch = bytes([hi, lo]).decode('gb2312')
            except Exception:
                continue
            common.add(ord(ch))
    common |= set(chars)           # never drop a character we actually translate
    broad = []
    broad.append((0x0020, 0x007E))
    broad.append((0x00A0, 0x00FF))
    broad.append((0x2000, 0x206F))
    broad.append((0x3000, 0x303F))
    broad.append((0x3040, 0x30FF))
    broad.append((0xFF00, 0xFFEF))
    cs = sorted(common)
    i = 0
    while i < len(cs):
        j = i
        while j + 1 < len(cs) and cs[j+1] == cs[j] + 1:
            j += 1
        broad.append((cs[i], cs[j]))
        i = j + 1
    broad.sort()

    lines = []
    lines.append('/* AUTO-GENERATED by tools/gen_translations.py -- do not edit */')
    lines.append('#pragma once')
    lines.append('#ifndef PARSEC_ZH_TRANSLATIONS_H')
    lines.append('#define PARSEC_ZH_TRANSLATIONS_H')
    lines.append('')
    lines.append('#define TR_N %d' % len(items))
    lines.append('')
    lines.append('static const char* const TR_EN[TR_N] = {')
    for en, zh in items:
        lines.append('  ' + cstr(en) + ',')
    lines.append('};')
    lines.append('')
    lines.append('static const char* const TR_ZH[TR_N] = {')
    for en, zh in items:
        lines.append('  ' + cstr(zh) + ',')
    lines.append('};')
    lines.append('')
    lines.append('/* ImWchar (unsigned short) ranges: ASCII + punctuation + used CJK codepoints */')
    lines.append('static const unsigned short TR_GLYPH_RANGES[] = {')
    row = []
    for a, b in ranges:
        row.append('0x%04X,0x%04X,' % (a, b))
        if len(row) == 4:
            lines.append('  ' + ''.join(row)); row = []
    if row:
        lines.append('  ' + ''.join(row))
    lines.append('  0x0000')
    lines.append('};')
    lines.append('')
    lines.append('/* Broad ranges: ASCII + punctuation + common Simplified Chinese (GB2312 L1),')
    lines.append('   so dynamic/user text can be drawn too (not just dictionary words). */')
    lines.append('static const unsigned short TR_GLYPH_RANGES_BROAD[] = {')
    row = []
    for a, b in broad:
        row.append('0x%04X,0x%04X,' % (a, b))
        if len(row) == 4:
            lines.append('  ' + ''.join(row)); row = []
    if row:
        lines.append('  ' + ''.join(row))
    lines.append('  0x0000')
    lines.append('};')
    lines.append('')
    lines.append('#endif')
    out = os.path.join(root, 'src', 'translations.h')
    os.makedirs(os.path.dirname(out), exist_ok=True)
    open(out, 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
    print('entries=%d cjk_chars=%d ranges=%d broad_chars=%d broad_ranges=%d -> %s' %
          (len(items), len(cjk), len(ranges), len(common), len(broad), out))

if __name__ == '__main__':
    main()
